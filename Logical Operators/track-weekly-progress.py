# Assignment Operators → Track Weekly Progress

score = 0

score += 10   # +10 for drinking water daily      → 10
score += 15   # +15 for exercise                  → 25
score *= 2    # Double your score on bonus week  → 50
score -= 5    # -5 for skipping sleep              → 45
score /= 2    # Split between two categories      → 22.5
score //= 1   # Keep whole number                  → 22

print(f"Final habit score: {score}")
